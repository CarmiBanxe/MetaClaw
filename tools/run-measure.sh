#!/usr/bin/env bash
# Запуск меры с ЧЕСТНЫМ кодом возврата.
#
# ЗАЧЕМ ЭТО ЕСТЬ. Правило «`$?` после конвейера есть код ПОСЛЕДНЕЙ команды конвейера, а не меры»
# было записано 2026-09-10 и нарушено его же автором 2026-09-11: `мера | tail` с последующим
# `КОД=$?` показал `0` при настоящем `1`, и красная мера была прочитана как зелёная.
#
# Правило, нарушенное автором ПОСЛЕ записи, записью не лечится (R31). Поэтому оно здесь, а не в
# прозе: вывод уходит в файл, код снимается отдельной строкой, конвейера в месте снятия нет.
#
# ИМЕНА ПЕРЕМЕННЫХ ЛАТИНСКИЕ — НАМЕРЕННО. Первая редакция этого файла была написана кириллицей и
# не запустилась: bash не берёт кириллические имена. Это ВТОРОЕ за такт нарушение собственного
# записанного правила, и оно на своём месте — в комментарии рядом с кодом, а не в отдельной прозе.
#
# Применение:  tools/run-measure.sh <каталог> <команда...>
# Печатает:    КОД=<n> · путь к полному выводу · последние строки (число строк — TAIL_LINES)
#
# ВЕРШИНА ПЕЧАТАЕТСЯ ЗДЕСЬ ЖЕ — добавлено 2026-09-11 после ТРЕТЬЕГО нарушения того же рода.
# Автор сняла вершину одной командой, меру прогнала другой минутами позже, и между ними легло чужое
# объявление: запись назвала числа верные, а вершину — неверную (R46, R54b). Правило «вершина
# снимается в том же такте, что и замер» держится не памятью, а ОДНОЙ КОМАНДОЙ. Отсюда вершина,
# чистота дерева и код возврата выходят из одного вызова и разойтись не могут.
#
# ПРЕДЕЛ, объявленный: скрипт снимает КОД, а не смысл. Мера, поймавшая собственное исключение и
# вернувшая ноль, будет прочитана как прошедшая — различить это отсюда нечем.
set -u
if [ "$#" -lt 2 ]; then
  echo "usage: run-measure.sh <каталог> <команда...>" >&2
  exit 2
fi
root="$1"; shift
out="$(mktemp "${TMPDIR:-/tmp}/measure-XXXXXX.txt")"

# Вершина и чистота — ДО прогона, из того же каталога: после прогона дерево могло сдвинуться.
head="$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo "не-репозиторий")"
dirty="$(git -C "$root" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"

( cd "$root" && "$@" ) > "$out" 2>&1
code=$?                      # ← отдельной строкой, сразу, без конвейера

after="$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo "не-репозиторий")"

echo "ВЕРШИНА=$head грязных=$dirty"
if [ "$head" != "$after" ]; then
  echo "ВЕРШИНА СДВИНУЛАСЬ ВО ВРЕМЯ ЗАМЕРА: $head → $after — предмет менялся под прибором" >&2
fi
echo "КОД=$code"
echo "ВЫВОД=$out"
echo "--- последние строки ---"
tail -n "${TAIL_LINES:-15}" "$out"
exit "$code"
