#!/usr/bin/env bash
# Коммит с ПРОВЕРКОЙ, что он лёг, и отправкой только после неё.
#
# ЗАЧЕМ ЭТО ЕСТЬ — два дефекта, каждый пойманный на себе 2026-09-11.
#
# (1) ЛОЖНОЕ ПОДТВЕРЖДЕНИЕ. `git commit && git push && echo запушено` напечатало «запушено»
#     при ОТКЛОНЁННОМ крючком коммите: отправлять было нечего, push вернул 0. Слово об успехе
#     пришло от команды, которая ничего не делала.
#
# (2) КИРИЛЛИЦА В ИМЕНАХ ПЕРЕМЕННЫХ. bash их не берёт. Четыре раза за такт: `SHA_ДО=...` →
#     «command not found», обе переменные пусты, `[ "$ДО" = "$ПОСЛЕ" ]` сравнило пустоту с
#     пустотой и ушло в ветвь «лёг» — ВЕРНЫЙ ответ по НЕВЕРНОЙ причине. Проверка, дающая
#     правильный ответ случайно, хуже отсутствующей: она внушает доверие.
#
# Поэтому здесь: имена латинские, HEAD сверяется до и после, push — только если HEAD сдвинулся.
#
# (3) `git add -A` БЕЗ ПУТЕЙ. Первая редакция при отсутствии путей брала ВСЁ — и первая же проба
#     утащила в коммит два чужих изменения и файл-мусор, оставшийся от сломанного скрипта.
#     Поэтому пути ОБЯЗАТЕЛЬНЫ: помощник, умеющий захватить лишнее, однажды захватит.
#
# Применение:  tools/commit-verified.sh <файл-сообщения|-> <путь> [пути...]
set -u
if [ "$#" -lt 2 ]; then
  echo "usage: commit-verified.sh <msgfile|-> <path> [paths...]" >&2
  echo "  пути ОБЯЗАТЕЛЬНЫ: add -A без них забирает чужие изменения" >&2
  exit 2
fi
msg="$1"; shift
git add -A -- "$@"

before=$(git rev-parse HEAD)
if [ "$msg" = "-" ]; then git commit -q -F -; else git commit -q -F "$msg"; fi
rc=$?
after=$(git rev-parse HEAD)

if [ "$before" = "$after" ]; then
  echo "КОММИТ НЕ ЛЁГ: HEAD не сдвинулся ($before), код commit=$rc" >&2
  echo "  — крючок отклонил, либо нечего коммитить. Отправка НЕ делается." >&2
  git status --porcelain | head -10 >&2
  exit 1
fi
echo "коммит лёг: $after"
git push -q origin "$(git rev-parse --abbrev-ref HEAD)" || { echo "ОТПРАВКА НЕ УДАЛАСЬ" >&2; exit 1; }
echo "отправлено"
