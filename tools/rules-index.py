#!/usr/bin/env python3
"""Указатель правил свода — ПОРОЖДАЕТСЯ, а не пишется рукой.

ЗАЧЕМ МАШИНОЙ. Указатель есть пересказ содержания, а пересказ устаревает во всех копиях сразу
(R51). Рукописный указатель к файлу, который правят каждый такт, разойдётся с ним на второй день
и будет читаться как истина. Порождённый — расходиться не может: он есть выборка из самого файла.

ЧТО ДЕЛАЕТ. Собирает все заголовки вида `## R<N>` и `### R<N>` вместе с их одной строкой смысла
и кладёт между метками. Идемпотентен: повторный прогон даёт тот же файл побайтово.

ПРЕДЕЛ, ОБЪЯВЛЕННЫЙ. Указатель показывает заголовки, а не содержание правил: правило, чей заголовок
лжёт о его теле, пройдёт сюда неизменным. Это не проверка смысла и ею не притворяется.
"""

import pathlib
import re
import sys

НАЧАЛО = "<!-- УКАЗАТЕЛЬ ПОРОЖДАЕТСЯ tools/rules-index.py — РУКОЙ НЕ ПРАВИТЬ -->"
КОНЕЦ_ = "<!-- КОНЕЦ УКАЗАТЕЛЯ -->"


def собрать(текст: str) -> str:
    строки = []
    for s in текст.splitlines():
        m = re.match(r"^(#{2,3})\s+(R\d+(?:–R\d+)?)\s+·\s+(.+?)\s*$", s)
        if m:
            уровень, имя, смысл = m.groups()
            if "–" in имя:  # сдвоенная шапка — не правило, а раздел
                continue
            строки.append(f"- **{имя}** · {смысл}")
    return "\n".join(строки)


def главное() -> int:
    путь = pathlib.Path(
        sys.argv[1] if len(sys.argv) > 1 else "/home/mmber/MetaClaw/specs/gap-probe-must-name-its-reddening.md"
    )
    текст = путь.read_text(encoding="utf-8")
    указатель = собрать(текст)
    число = len(указатель.splitlines())
    блок = f"{НАЧАЛО}\n\n## Указатель правил ({число})\n\n{указатель}\n\n{КОНЕЦ_}"

    if НАЧАЛО in текст and КОНЕЦ_ in текст:
        до = текст.split(НАЧАЛО)[0]
        после = текст.split(КОНЕЦ_, 1)[1]
        новый = до + блок + после
    else:
        # вставить после первого абзаца-врезки, перед первым правилом
        метка = "\n## Правило 1."
        if метка not in текст:
            print("не нашлось места для вставки: нет «## Правило 1.»", file=sys.stderr)
            return 1
        до, после = текст.split(метка, 1)
        новый = до + с_переводом(блок) + метка + после

    if новый != текст:
        путь.write_text(новый, encoding="utf-8")
    print(f"указатель: {число} правил · файл {'обновлён' if новый != текст else 'без изменений'}")
    return 0


def с_переводом(блок: str) -> str:
    return блок + "\n"


if __name__ == "__main__":
    sys.exit(главное())
