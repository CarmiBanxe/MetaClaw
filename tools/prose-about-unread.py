#!/usr/bin/env python3
"""Меры, утверждающие нечто о файле — ВНУТРИ ФРАЗЫ, а не обращением к нему.

ЗАЧЕМ. 2026-09-11 у меры полной цепи нашлось вот что:

    НЕМОТА = {
      "2 обязательство":     "governance/regulatory-threshold-homes.json не называет ни одной функции",
      "10 процесс/evidence": "governance/security/e2e-scenarios.json не называет ни одной функции",
    }

Мера этих реестров НЕ ОТКРЫВАЛА. Утверждение было истинным в день написания и осталось бы
печататься, став ложным. Я процитировала его как замер и построила на нём разбор (R36).

ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ПРИБОРА ИСКАЛА НЕ ТО, и это стоит записи. Она требовала, чтобы признак чтения
(`open`, `read_text`, …) стоял на ТОЙ ЖЕ СТРОКЕ, что и путь. Меры же пишут
`P = Path("governance/x.json")`, а читают `P.read_text()` строкой ниже. Прибор дал 184 «находки»,
среди них файлы, которые мера заведомо читает. Он измерил СОБСТВЕННУЮ УЗОСТЬ — пятый случай этого
разряда за один день.

РАЗЛИЧИТЕЛЬ ВЗЯТ ИНОЙ И ПРЕДМЕТНЫЙ: путь ВНУТРИ ФРАЗЫ против пути как САМОСТОЯТЕЛЬНОГО литерала.

    "governance/regulatory-threshold-homes.json не называет ни одной функции"   ← фраза: УТВЕРЖДЕНИЕ
    Path("governance/regulatory-threshold-homes.json")                          ← литерал: ОБРАЩЕНИЕ

Прибор ищет пути, встречающиеся ТОЛЬКО во фразах и ни разу — самостоятельным литералом. Мера,
которая о файле рассуждает и никогда к нему не обращается, рассуждает по памяти автора.

ПРЕДЕЛ, ОБЪЯВЛЕННЫЙ И ПЕЧАТАЕМЫЙ ВСЕГДА. Вывод есть СПИСОК МЕСТ ДЛЯ ЧТЕНИЯ, не перечень дефектов:

  (1) путь может собираться из частей либо приходить доводом — тогда самостоятельного литерала нет
      вовсе, и прибор назовёт чтение прозой ложно;
  (2) упоминание во фразе бывает законным: ссылка на соседнюю меру, адрес в доводе, исторический
      след. Не всякая фраза есть утверждение О СОДЕРЖАНИИ;
  (3) обратного прибор не ловит ВОВСЕ: заготовленную причину, не называющую пути («предмет
      отсутствует»), он не увидит ни при каком поведении. Это его главная слепота.

Применение:  python3 tools/prose-about-unread.py <корень дерева>
             python3 tools/prose-about-unread.py --self-test
"""

from __future__ import annotations

import pathlib
import re
import sys
import tempfile

PATHPAT = r"[A-Za-z0-9_./-]+/[A-Za-z0-9_.-]+\.(?:json|yaml|yml|md|ts|py|cjs|mjs)"
BARE = re.compile(r"""["'](""" + PATHPAT + r""")["']""")
ANY = re.compile(PATHPAT)


def measure(text: str) -> set[str]:
    """Пути, названные ТОЛЬКО во фразе. Работает над текстом — зовётся и пробой, и прогоном.

    Различитель ТОЧНЫЙ, а не «слово рядом»: берётся ЦЕЛИКОМ строковый литерал, содержащий путь,
    и сравнивается с самим путём. Совпал — это ОБРАЩЕНИЕ. Не совпал (в литерале есть что-то ещё) —
    это ФРАЗА. Первая редакция искала слово по соседству и пропускала `"см. governance/x.json"`,
    где соседнее слово короче трёх букв; самотест это поймал ДО публикации числа.
    """
    литералы = re.findall(r"'([^'\n]*)'|\"([^\"\n]*)\"", text)
    обращения: set[str] = set()
    фразы: set[str] = set()
    for a, b in литералы:
        s = a or b
        m = ANY.search(s)
        if not m:
            continue
        путь = m.group(0)
        (обращения if s.strip() == путь else фразы).add(путь)
    return фразы - обращения


def self_test() -> int:
    """Проба обязана РАЗЛИЧАТЬ фразу и обращение, иначе прибор меряет собственную узость."""
    bad = 0
    случаи = [
        ('X = {"a": "governance/x.json не называет ни одной функции"}', {"governance/x.json"}, "фраза"),
        ('P = Path("governance/x.json")\nd = json.loads(P.read_text())', set(), "обращение"),
        (
            'P = Path("governance/x.json")  # governance/x.json не называет функций',
            set(),
            "обращение плюс фраза → обращение сильнее",
        ),
        (
            'print("см. governance/x.json")',
            {"governance/x.json"},
            "ссылка во фразе — ловится, и это ЛОЖНОЕ срабатывание по пределу (2)",
        ),
    ]
    for текст, ждём, имя in случаи:
        вышло = measure(текст)
        if вышло != ждём:
            bad += 1
            print(f"  САМОТЕСТ ПРОВАЛ [{имя}]: ждали {ждём or 'пусто'}, вышло {вышло or 'пусто'}")
    print(f"самотест: случаев {len(случаи)}, провалов {bad}")
    return 1 if bad else 0


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    if len(sys.argv) < 2:
        print("usage: prose-about-unread.py <корень> | --self-test", file=sys.stderr)
        return 2
    root = pathlib.Path(sys.argv[1])
    scripts = sorted((root / "scripts").glob("*.py"))
    print(f"ВСЕЛЕННАЯ: {len(scripts)} мер в {root}/scripts/*.py")
    rows: list[tuple[str, str]] = []
    for s in scripts:
        text = s.read_text(encoding="utf-8", errors="replace")
        for q in sorted(measure(text)):
            if (root / q).exists():
                rows.append((s.name, q))
    print(f"ПУТЕЙ, НАЗВАННЫХ ТОЛЬКО ВО ФРАЗЕ: {len(rows)} (ВЕРХНЯЯ ГРАНИЦА — см. шапку)\n")
    by: dict[str, list[str]] = {}
    for m, q in rows:
        by.setdefault(m, []).append(q)
    for m in sorted(by, key=lambda k: -len(by[k]))[:12]:
        print(f"  {m}  ({len(by[m])})")
        for q in by[m][:3]:
            print(f"      {q}")
    print(
        "\nПРЕДЕЛ, печатается всегда: это СПИСОК МЕСТ ДЛЯ ЧТЕНИЯ, а не перечень дефектов. "
        "Путь, собранный из частей либо пришедший доводом, будет назван прозой ложно; "
        "законная ссылка во фразе — тоже; а заготовленную причину БЕЗ пути прибор не увидит вовсе."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
