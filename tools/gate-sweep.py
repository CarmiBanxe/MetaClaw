#!/usr/bin/env python3
"""Обход мер дерева, различающий ТРИ исхода, а не два.

**Ради какой ошибки заведён.** 2026-09-10 центральный терминал обошёл гейты, ища слова
`FAIL|НЕ ПРОЙДЕН` в последних двух строках вывода, и доложил «красных ноль». Четыре меры
сообщали об отказе КОДОМ ВОЗВРАТА, а не этими словами: обход взял у прибора удобный сигнал
вместо обещанного и ошибся в сторону «всё хорошо» — единственную, в которую ошибаться нельзя.

Через час тот же обход, запущенный в снимке `git archive` без `.git`, назвал КРАСНЫМИ две меры,
которые лишь не смогли отработать: они зовут `git ls-files`, тот падал, python возвращал
ненулевой код. Ошибка в другую сторону, причина одна.

**Отсюда три исхода, а не два.** ПРОШЛО · ОТКАЗАЛО · НЕ СМОГЛО ОТРАБОТАТЬ. Третий есть немота
прибора, и принимать её за суждение нельзя — ни в чью пользу.

**Признак немоты — трассировка исключения в выводе**, а не код возврата: у падения и отказа код
одинаков. Признак несовершенен и назван таковым ниже.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ТРАССА = ("Traceback (most recent call last)", "CalledProcessError")

# Скрипты, МЕНЯЮЩИЕ дерево либо ходящие наружу: обход их не запускает и говорит об этом вслух.
# Отбор здесь по существу, а не по имени: каждое имя внесено после чтения того, что скрипт делает.
МЕНЯЮЩИЕ = frozenset(
    {
        "guarded-merge.py",
        "merge-attestation.py",
        "imports-refresh.py",
        "migrate-overlay-keys.py",
        "build-provenance-digests.py",
        "parity-donor-run.py",
        "post-merge-coverage.py",
        "accept-authored-map.py",
        "emulation-revocation-test.py",
        "cross-repo-action-check.py",
        "merge-evidence-reconcile.py",
    }
)

# Код 2 у argparse есть НЕВЕРНЫЙ ВЫЗОВ, а не отказ меры: скрипт требует довода, которого обход
# не знает. Считать это отказом значило бы вменить предмету немоту обхода.
НЕВЕРНЫЙ_ВЫЗОВ = 2


def исход(путь: pathlib.Path, корень: pathlib.Path, таймаут: int) -> tuple[str, str]:
    """Один из трёх исходов и первая содержательная строка вывода.

    Мера запускается С РАБОЧИМ КАТАЛОГОМ ДЕРЕВА: почти все они читают дерево относительными
    путями и в чужом каталоге видят пустоту. Первая редакция обхода этого не делала, и меры
    честно ответили «universe is empty. Nothing matched is not the same as nothing is wrong» —
    их собственная честность поймала дефект обхода раньше меня.
    """
    try:
        r = subprocess.run(
            [sys.executable, str(путь.resolve())],
            capture_output=True,
            text=True,
            timeout=таймаут,
            cwd=str(корень.resolve()),
        )
    except subprocess.TimeoutExpired:
        return "НЕ СМОГЛО", f"не уложилось в {таймаут}с"
    вывод = (r.stdout or "") + (r.stderr or "")
    if any(t in вывод for t in ТРАССА):
        строки = [s for s in вывод.strip().split("\n") if s.strip()]
        return "НЕ СМОГЛО", строки[-1][:120] if строки else "исключение без сообщения"
    if r.returncode == 0:
        return "ПРОШЛО", ""
    if r.returncode == НЕВЕРНЫЙ_ВЫЗОВ and ("usage:" in вывод or "required" in вывод):
        return "НЕВЕРНЫЙ ВЫЗОВ", "требует довода, которого обход не знает"
    строки = [s for s in вывод.strip().split("\n") if s.strip()]
    return "ОТКАЗАЛО", строки[-1][:160] if строки else "отказ без сообщения"


def main() -> int:
    корень = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    таймаут = 60
    меры = sorted(м for м in (корень / "scripts").glob("*.py") if м.name not in МЕНЯЮЩИЕ)
    print(
        "ВСЕЛЕННАЯ, печатается всегда: все `scripts/*.py`, кроме МЕНЯЮЩИХ дерево. Прежняя "
        "редакция брала только `*gate*.py` — отбор ПО ИМЕНИ — и не видела 22 скрипта, среди "
        "них `bdr-roadmap-audit.py`, чей отказ нашла линия, а не обход."
    )
    print(f"  исключено как меняющее дерево: {len(МЕНЯЮЩИЕ)}")
    if not меры:
        print(
            f"обход: НЕ СМОГЛО — в {корень}/scripts нет ни одной меры. "
            "Пустая вселенная есть неисправность обхода, а не чистый прогон"
        )
        return 1
    счёт = {"ПРОШЛО": 0, "ОТКАЗАЛО": 0, "НЕ СМОГЛО": 0, "НЕВЕРНЫЙ ВЫЗОВ": 0}
    for м in меры:
        и, почему = исход(м, корень, таймаут)
        счёт[и] += 1
        if и != "ПРОШЛО":
            print(f"  {и:<10} {м.name}")
            if почему:
                print(f"             {почему}")
    всего = sum(счёт.values())
    print(
        f"\nмер {всего} = прошло {счёт['ПРОШЛО']} + отказало {счёт['ОТКАЗАЛО']}"
        f" + не смогло {счёт['НЕ СМОГЛО']} + неверный вызов {счёт['НЕВЕРНЫЙ ВЫЗОВ']}"
    )
    print(
        "ПРЕДЕЛ ОБХОДА, печатается всегда: немота опознаётся по трассировке в выводе — "
        "мера, поймавшая собственное исключение и вернувшая ненулевой код, будет "
        "засчитана ОТКАЗОМ. Различить их отсюда нечем: обход не знает предмета мер."
    )
    return 1 if счёт["ОТКАЗАЛО"] or счёт["НЕ СМОГЛО"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
