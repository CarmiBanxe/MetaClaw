# Чем запускается мера. Отбор по расширению здесь ЗАКОНЕН: он о способе запуска, а не о предмете.
ЧИТАЕТ_ИСТОРИЮ = re.compile(r"""git["\s,']+(log|show|cat-file|merge-base|rev-list|rev-parse|ls-tree|for-each-ref)""")


def читает_историю(путь: pathlib.Path) -> bool:
    """Мера, читающая ИСТОРИЮ git, а не только рабочие файлы.

    ЗАЧЕМ ОТДЕЛЬНАЯ КАТЕГОРИЯ. В снимке история заведена заново, и SHA прежнего дерева в ней не
    разрешаются. Такая мера отказывает НЕ ПОТОМУ, что дерево дефектно, а потому, что предмет её
    проверки в снимке отсутствует по построению.

    Найдено живым случаем 2026-09-11: `emulated-acceptance-separation-gate.py` отказал в снимке
    (`FABRICATED_SESSION_IDS`) и прошёл на дереве. Его проверка — что `evidence_commit_sha` несёт
    трейлер сессии и что SHA состоят в отношении предка — в снимке неисполнима.

    ГРАНИЦА ОБРАЗЦА ПРОВЕДЕНА ПО СУЩЕСТВУ, А НЕ ПО СЛОВУ «git». `git ls-files` читает ИНДЕКС, а не
    историю, и в снимке работает: `full-chain-coverage-gate.py` зовёт именно его и даёт в снимке
    построчно тот же ответ, что на дереве (сверено 2026-09-11). Дописать `ls-files` в образец
    значило бы назвать снимко-враждебной меру, которая таковой не является.

    ЭТО ПРЕДОСТЕРЕЖЕНИЕ, А НЕ ПРЕДСКАЗАНИЕ. Названная мера не обязана отказать в снимке:
    `parity-quarantine-gate.py` помечен и в снимке прошёл. Категория говорит «отказу здесь не
    верить без проверки на дереве», а не «здесь будет отказ».
    """
    try:
        return bool(ЧИТАЕТ_ИСТОРИЮ.search(путь.read_text(errors="ignore")))
    except OSError:
        return False


def ЖИВОЙ_ПРОГОН(имя: str) -> bool:
    """Живой прогон поднимает службу и пишет на диск. Обход его не запускает.

    Правилом, а не перечнем: перечень я писала рукой и пропустила ПЯТЬ из одиннадцати —
    `recon-door-live`, `safeguarding-door-live`, `sanctions-door-live`, `swift-door-live`,
    `treasury-live`. Все пять обход объявил ОТКАЗАВШИМИ, тогда как они лишь не нашли среды.
    Перечень, писанный рукой, есть тот же отбор по признаку, похожему на предмет.
    """
    return "-live." in имя or имя.endswith("-live.cjs") or "live" in имя.split(".")[0].split("-")


ЗАПУСК = {".py": [sys.executable], ".cjs": ["node"], ".mjs": ["node"], ".sh": ["bash"]}


def сорок_мер_вне_каталога(корень: pathlib.Path) -> list[str]:
    """Меры, лежащие ВНЕ `scripts/`. Обход их не запускает и обязан назвать поимённо.

    Немой пропуск неотличим от отсутствия предмета. Прежде обход брал вселенную из `scripts/` и
    ни разу не сказал, что `tools/secret-scan.py` существует.
    """
    найдено: list[str] = []
    for под in ("tools",):
        каталог = корень / под
        if not каталог.is_dir():
            continue
        for м in sorted(каталог.glob("*.py")):
            найдено.append(f"{под}/{м.name}")
    return найдено


def исход(путь: pathlib.Path, корень: pathlib.Path, таймаут: int) -> tuple[str, str]:
    """Один из трёх исходов и первая содержательная строка вывода.

    Мера запускается С РАБОЧИМ КАТАЛОГОМ ДЕРЕВА: почти все они читают дерево относительными
    путями и в чужом каталоге видят пустоту. Первая редакция обхода этого не делала, и меры
    честно ответили «universe is empty. Nothing matched is not the same as nothing is wrong» —
    их собственная честность поймала дефект обхода раньше меня.
    """
    try:
        r = subprocess.run(
            [*ЗАПУСК[путь.suffix], str(путь.resolve())],
            capture_output=True,
            text=True,
            timeout=таймаут,
            cwd=str(корень.resolve()),
        )
    except subprocess.TimeoutExpired:
        return "НЕ СМОГЛО", f"не уложилось в {таймаут}с"
    вывод = (r.stdout or "") + (r.stderr or "")
    if any(t in вывод for t in ТРАССА):
        строки = [s for s in вывод.strip().split("\n") if s.strip()]
        return "НЕ СМОГЛО", строки[-1][:120] if строки else "исключение без сообщения"
    if r.returncode == 0:
        return "ПРОШЛО", ""
    if r.returncode == НЕВЕРНЫЙ_ВЫЗОВ and ("usage:" in вывод or "required" in вывод):
        return "НЕВЕРНЫЙ ВЫЗОВ", "требует довода, которого обход не знает"
    строки = [s for s in вывод.strip().split("\n") if s.strip()]
    return "ОТКАЗАЛО", строки[-1][:160] if строки else "отказ без сообщения"


