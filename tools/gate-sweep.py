"""Обход мер дерева, различающий ТРИ исхода, а не два.

**Ради какой ошибки заведён.** 2026-09-10 центральный терминал обошёл гейты, ища слова
`FAIL|НЕ ПРОЙДЕН` в последних двух строках вывода, и доложил «красных ноль». Четыре меры
сообщали об отказе КОДОМ ВОЗВРАТА, а не этими словами: обход взял у прибора удобный сигнал
вместо обещанного и ошибся в сторону «всё хорошо» — единственную, в которую ошибаться нельзя.

Через час тот же обход, запущенный в снимке `git archive` без `.git`, назвал КРАСНЫМИ две меры,
которые лишь не смогли отработать: они зовут `git ls-files`, тот падал, python возвращал
ненулевой код. Ошибка в другую сторону, причина одна.

**Отсюда три исхода, а не два.** ПРОШЛО · ОТКАЗАЛО · НЕ СМОГЛО ОТРАБОТАТЬ. Третий есть немота
прибора, и принимать её за суждение нельзя — ни в чью пользу.

**Признак немоты — трассировка исключения в выводе**, а не код возврата: у падения и отказа код
одинаков. Признак несовершенен и назван таковым ниже.
"""

