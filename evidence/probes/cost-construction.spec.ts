import { cost, Budget } from "./budget";

const код = (f: () => unknown): string => {
  try { f(); return "НЕ БРОСИЛ"; } catch (e) { return (e as { code?: string }).code ?? "ОТКАЗ"; }
};

describe("стоимость: проверка КОНСТРУКЦИИ, а не границы", () => {
  it("NEGATIVE_COST — отрицательная величина не строится", () => {
    expect(код(() => cost(-1))).toBe("NEGATIVE_COST");
    expect(код(() => cost(-0.0001))).toBe("NEGATIVE_COST");
  });

  it("COST_UNREADABLE — нечисло и бесконечность не строятся", () => {
    for (const плохое of [Number.NaN, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY]) {
      expect(код(() => cost(плохое))).toBe("COST_UNREADABLE");
    }
  });

  it("ПОРЯДОК: нечитаемое ловится РАНЬШЕ отрицательного", () => {
    // -Infinity отрицательна И нечитаема; отказ обязан назвать первую причину, а не вторую.
    expect(код(() => cost(Number.NEGATIVE_INFINITY))).toBe("COST_UNREADABLE");
  });

  it("КОНТРОЛЬ: ноль и положительное строятся", () => {
    expect(код(() => cost(0))).toBe("НЕ БРОСИЛ");
    expect(код(() => cost(12.5))).toBe("НЕ БРОСИЛ");
  });

  it("отрицательное МОЖЕТ прийти из арифметики — тип этого не ловит, ловит конструктор", () => {
    // Тип запрещает НАПИСАТЬ -1. Но `cost()` принимает обычное число, и разность двух величин
    // легко даёт отрицательное во время исполнения. Здесь работает уже не тип, а проверка.
    const было = 10, стало = 12;
    expect(код(() => cost(было - стало))).toBe("NEGATIVE_COST");
  });

  it("построенная стоимость расходуется бюджетом", () => {
    const b = new Budget(10);
    b.charge(cost(4), "plan");
    expect(b.state.spent).toBe(4);
  });
});
