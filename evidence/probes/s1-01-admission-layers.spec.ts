import { admit } from "./action-admission";

const ОСНОВА = { envelopeId: "env-1", subject: "payment.send",
                 allowed: ["payment.send"], prohibited: [] as string[] };

/** Тип `Admission` — размеченное объединение: код отказа НЕЛЬЗЯ прочесть, не проверив исход.
 *  Это и есть страж, держащийся ТИПОМ: «прошло» и «код отказа» не сосуществуют. */
const исход = (a: ReturnType<typeof admit>): string =>
  a.permitted ? "ПРОШЛО" : a.refusalCode;

describe("S1-01 · разрешение не отменяет запрета", () => {
  it("ЗАПРЕТ СИЛЬНЕЕ РАЗРЕШЕНИЯ: то же действие и разрешено, и запрещено", () => {
    const a = admit({ ...ОСНОВА, prohibited: ["payment.send"] } as never);
    expect(исход(a)).toBe("ACTION_PROHIBITED");
  });

  it("ЗАПРЕТ МОДЕЛИ не снимается разрешением полномочия", () => {
    // Конверт разрешает действие. Актор — модель. Глагол классифицирован DENY.
    const a = admit({ ...ОСНОВА, verb: "execute", actorIsModel: true } as never);
    expect(исход(a)).toBe("MODEL_MAY_NOT");
  });

  it("ПОРЯДОК: запрет действия проверяется РАНЬШЕ классификации глагола", () => {
    // Оба нарушения сразу. Отказ обязан назвать первую причину, а не последнюю.
    const a = admit({ ...ОСНОВА, prohibited: ["payment.send"],
                      verb: "execute", actorIsModel: true } as never);
    expect(исход(a)).toBe("ACTION_PROHIBITED");
  });

  it("ОТЗЫВ сильнее всего: отозванный конверт не спасает ни разрешение, ни глагол", () => {
    const a = admit({ ...ОСНОВА, revoked: true, verb: "explain", actorIsModel: false } as never);
    expect(исход(a)).toBe("AUTHORITY_REVOKED");
  });

  it("КОНТРОЛЬ: разрешённое действие разрешённым глаголом проходит", () => {
    const a = admit({ envelopeId: "env-1", subject: "report.explain",
                      allowed: ["report.explain"], prohibited: [],
                      verb: "explain", actorIsModel: true } as never);
    expect(исход(a)).toBe("ПРОШЛО");
  });

  it("КОНТРОЛЬ: НЕ-модель тем же глаголом проходит — запрет адресован модели", () => {
    const a = admit({ ...ОСНОВА, verb: "execute", actorIsModel: false } as never);
    expect(исход(a)).toBe("ПРОШЛО");
  });
});
