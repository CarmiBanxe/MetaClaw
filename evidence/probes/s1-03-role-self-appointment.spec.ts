import { SandboxHolders, assertHolders } from "./holders";
import type { OrgRole } from "./roles";

const РЕЕСТР = new SandboxHolders(new Map([
  ["MLRO", "sim://sandbox/MLRO"], ["CEO", "sim://sandbox/CEO"], ["CFO", "sim://sandbox/CFO"],
] as [OrgRole, string][]));

const код = (кто: string, роли: readonly string[]): string => {
  try { assertHolders(РЕЕСТР, кто, роли as never, "sandbox"); return "ПРОШЛО"; }
  catch (e) { return (e as { code?: string }).code ?? "ОТКАЗ"; }
};

describe("S1-03 · самоназначение роли через тело запроса", () => {
  it("КОНТРОЛЬ: своя роль своим держателем — проходит", () => {
    expect(код("sim://sandbox/MLRO", ["MLRO"])).toBe("ПРОШЛО");
  });

  it("ЧУЖАЯ РОЛЬ: держатель MLRO заявляет CEO", () => {
    expect(код("sim://sandbox/MLRO", ["CEO"])).toBe("HOLDER_MISMATCH");
  });

  it("ДОБАВЛЕННАЯ РОЛЬ: своя + чужая в одном заявлении", () => {
    // Самый тихий способ: одну роль держу, вторую приписал. Проверка обязана смотреть КАЖДУЮ.
    expect(код("sim://sandbox/MLRO", ["MLRO", "CEO"])).toBe("HOLDER_MISMATCH");
  });

  it("ПОРЯДОК не спасает: чужая роль ПЕРВОЙ", () => {
    expect(код("sim://sandbox/MLRO", ["CEO", "MLRO"])).toBe("HOLDER_MISMATCH");
  });

  it("НЕСУЩЕСТВУЮЩАЯ роль в заявлении", () => {
    expect(код("sim://sandbox/MLRO", ["ПРИДУМАННАЯ"])).not.toBe("ПРОШЛО");
  });

  it("ПОСТОРОННИЙ с чужой строкой", () => {
    expect(код("посторонний", ["MLRO"])).toBe("HOLDER_MISMATCH");
  });
});
