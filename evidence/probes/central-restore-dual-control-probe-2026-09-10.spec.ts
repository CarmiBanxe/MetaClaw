/**
 * ПРОБА ЦЕНТРАЛЬНОГО ТЕРМИНАЛА — §5, двойной контроль восстановления. РЕДАКЦИЯ 2, 2026-09-10.
 *
 * ЧТО ОНА НАШЛА (редакция 1). `assertDualControl` проверяет четыре вещи и все четыре хорошо:
 * одобрений не менее двух · одобряющие различны · у каждого названо основание · ни один не есть
 * сам движок. И ровно поэтому не стерегла ничего: `approvals` приходили ИЗ ТЕЛА ЗАПРОСА.
 * Строгость правила была приложена к бумаге, которую заполняет тот, кого правило ограничивает.
 * Проба прошла все четыре проверки двумя самописными именами.
 *
 * ЧТО СДЕЛАЛА ЛИНИЯ. Завела порт записанных одобрений. Дерево называет эту пробу по имени в
 * `services/banksy/conductor/src/http/server.ts:297` как источник находки. Дверь
 * `/v0/director/restore` теперь: берёт одобрения ИЗ ЗАПИСИ, а не из тела · требует, чтобы за
 * каждым одобряющим числилось место в реестре · отвергает просителя среди одобряющих · сверяет
 * поле тела с записью «ради внятности отказа, а не ради безопасности: вниз всё равно уходит
 * запись» · и НЕСОБРАННЫЙ порт есть ОТКАЗ МАРШРУТА, а не разрешение.
 *
 * ПОЧЕМУ РЕДАКЦИЯ 2 СУЩЕСТВУЕТ. Редакция 1 осталась КРАСНОЙ и после починки — потому что зовёт
 * библиотеку НАПРЯМУЮ, минуя дверь, а библиотека происхождения одобрений не устанавливает и
 * никогда не обещала. Красная проба, чей предмет починен в другом месте, есть **постоянная
 * ложная тревога**: она учит проходить мимо красного. Это хуже, чем её отсутствие.
 *
 * Отсюда редакция 2 говорит ровно то, что измерено, и потому ЗЕЛЕНА:
 *   1) библиотека проверяет ЧЕТЫРЕ вещи — и проверяет их исправно;
 *   2) библиотека НЕ устанавливает происхождения одобрений, и это её граница, а не порок;
 *   3) гарантию даёт дверь, и место гарантии названо здесь, чтобы его не искали заново.
 *
 * ТРИ КАНАРЕЙКИ, ПРОВЕДЁННЫЕ 2026-09-10, каждая роняет РОВНО свою пробу:
 *   `approvals.length < 2` → `< 1`                     →  1 failed, 3 passed
 *   различие одобряющих ослеплено (ключ + индекс)      →  1 failed, 3 passed
 *   `МИНИМУМ_ОСНОВАНИЯ = 8` → `0`                      →  1 failed, 3 passed
 *
 * И ВТОРАЯ КАНАРЕЙКА НАШЛА ДЕФЕКТ В САМОЙ ПРОБЕ. Первая редакция второго случая давала второму
 * одобрению основание «ещё раз» — СЕМЬ знаков при `МИНИМУМ_ОСНОВАНИЯ = 8`. Его отвергала проверка
 * ДЛИНЫ ОСНОВАНИЯ, а не различия одобряющих: ослепление различия не роняло пробу ВОВСЕ.
 * Проба называла один страж и мерила другой — тот же дефект, что у проверки по классу, только
 * с другой стороны. Исправлено: основания уравнены, коды названы поимённо.
 *
 * ЧЕГО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ: что дверь исправна. Это иной предмет и иной прогон —
 * `central-a12-end-to-end`.
 */
import { assertDualControl } from "./restore-dual-control";

const код = (f: () => unknown): string => {
  try { f(); return "ПРИНЯТО"; } catch (e) { return (e as { code?: string }).code ?? "ОТКАЗ"; }
};
const одобрение = (by: string, reason = "восстановление согласовано") =>
  ({ by, reason, at: "2026-09-10T00:00:00Z" });

describe("§5: что библиотека двойного контроля проверяет и чего НЕ обещает", () => {
  it("ПРОВЕРЯЕТ: одно одобрение отвергается", () => {
    expect(код(() => assertDualControl([одобрение("sim://sandbox/CEO")], { sandbox: true })))
      .toBe("RESTORE_WITHOUT_DUAL_CONTROL");
  });

  it("ПРОВЕРЯЕТ: два одобрения ОДНОГО лица одобрениями двоих не являются", () => {
    // ОСНОВАНИЯ ОДИНАКОВО ДЛИННЫ НАМЕРЕННО. Первая редакция давала второму «ещё раз», и его
    // отвергала проверка ДЛИНЫ ОСНОВАНИЯ, а не различия одобряющих: канарейка, ослепившая
    // различие, не уронила эту пробу вовсе. Проба называла один страж и мерила другой.
    expect(код(() => assertDualControl(
      [одобрение("sim://sandbox/CEO"), одобрение("sim://sandbox/CEO")], { sandbox: true })))
      .toBe("RESTORE_APPROVERS_NOT_DISTINCT");
  });

  it("ПРОВЕРЯЕТ: одобрение без основания одобрением не является", () => {
    expect(код(() => assertDualControl(
      [одобрение("sim://sandbox/CEO"), { by: "sim://sandbox/CFO", reason: "", at: "x" }],
      { sandbox: true }))).toBe("RESTORE_APPROVER_WITHOUT_REASON");
  });

  it("НЕ УСТАНАВЛИВАЕТ ПРОИСХОЖДЕНИЯ: два самописных имени проходят — и это ГРАНИЦА библиотеки", () => {
    // Ровно то, что приходило из тела запроса до починки. Библиотека принимает: у неё нет и не
    // может быть способа узнать, кто написал эту бумагу. Гарантию даёт дверь — см. шапку.
    expect(код(() => assertDualControl(
      [одобрение("sim://sandbox/CEO"), одобрение("sim://sandbox/CFO")], { sandbox: true })))
      .toBe("ПРИНЯТО");
  });
});
