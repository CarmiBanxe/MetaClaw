import { append, AuditRefusal } from "./audit";

const код = (f: () => unknown): string => {
  try { f(); return "НЕ БРОСИЛ"; } catch (e) { return (e as AuditRefusal).code ?? String(e); }
};
const з = (seq: number) => ({ seq, event: "DECISION_RECEIVED", correlationId: "c1" }) as never;

describe("APPEND_ONLY_VIOLATED — достижимость", () => {
  it("следом, построенным самим append, — недостижим: ловит проверка непрерывности", () => {
    let t: readonly unknown[] = [];
    for (let i = 1; i <= 5; i++) t = append(t as never, з(i));
    expect(код(() => append(t as never, з(3)))).toBe("SEQUENCE_BROKEN");
    expect(код(() => append(t as never, з(5)))).toBe("SEQUENCE_BROKEN");
  });

  it("следом, испорченным извне, — достижим", () => {
    const испорчен = [з(3), з(2)] as never;
    expect(код(() => append(испорчен, з(3)))).toBe("APPEND_ONLY_VIOLATED");
  });
});
